void RenderGraphTexture::create(const Desc &desc, void *allocator) {
	texture = static_cast<ResourceManager *>(allocator)->acquireTexture(desc);
}

void RenderGraphTexture::destroy(const Desc &desc, void *allocator) {
	static_cast<ResourceManager *>(allocator)->releaseTexture(desc, texture);
}

std::string RenderGraphTexture::toString(const Desc &desc) {
	return std::format("texture {}x{} {}", desc.size.x(), desc.size.y(), ::toString(desc.format));
}

uint32_t std::hash<RenderGraphTexture::Desc>::operator()(const RenderGraphTexture::Desc &desc) const {
	uint32_t h = 0;
	hashCombine(h, desc.format, desc.size.x(), desc.size.y());
	return h;
}