#define DECLARE_COLOR(name, r, g, b) const Color name = Color(r, g, b);
#define DECLARE_COLOR_BYTE(name, r, g, b) DECLARE_COLOR(name, r / 255.f, g / 255.f, b / 255.f)
#define DECLARE_COLOR_ALIAS(name, alias) const Color alias = name;

#include <cstdint>

struct Color {
	float r, g, b;
	float a = 1.f;

	Color();
	explicit Color(float r, float g, float b, float a = 1.f);
	explicit Color(uint8_t r, uint8_t g, uint8_t b, uint8_t a = 255);
	explicit Color(int r, int g, int b, int a = 255);

	Vec3f toVec3() const;
	Vec4f toVec4() const;

	Color withAlpha(float alpha) const;
	Color darken(float by) const;
	Color lighten(float by) const;
};

